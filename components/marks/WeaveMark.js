const DEFAULT_COLOR = 'var(--color-plum)'
const GRADIENT_ID = 'weaveGrad'

function GradientDef({ colors }) {
  if (!colors) return null
  return (
    <defs>
      <linearGradient id={GRADIENT_ID} x1="41%" y1="1%" x2="59%" y2="99%">
        <stop offset="15.5%" stopColor={colors[0]} />
        <stop offset="52.1%" stopColor={colors[1]} />
        <stop offset="89.7%" stopColor={colors[2]} />
      </linearGradient>
    </defs>
  )
}

export default function WeaveMark({ animate = false, delay = 0, replay = 0, className, onDrawComplete, showBrush = false, color, gradientColors }) {
  const fillColor = gradientColors ? `url(#${GRADIENT_ID})` : (color || DEFAULT_COLOR)
  const svgRef = useRef(null)
  const [brushVisible, setBrushVisible] = useState(false)

  useEffect(() => {
    if (!animate) return

    const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches
    if (prefersReduced) {
      setBrushVisible(true)
      return
    }

    // Reset state for replay
    setBrushVisible(false)

    import('gsap').then(({ gsap }) => {
      const path = svgRef.current?.querySelector('path')
      if (!path) return

      // Measure and set up strokeDasharray
      const length = path.getTotalLength()
      path.style.strokeDasharray = length
      path.style.strokeDashoffset = length

      const effectiveDelay = replay > 0 ? 0 : delay

      // Animate draw-on from top-left to bottom-right
      gsap.to(path, {
        strokeDashoffset: 0,
        duration: 1.8,
        ease: 'power2.inOut',
        delay: effectiveDelay,
        onComplete: () => {
          setTimeout(() => {
            setBrushVisible(true)
            onDrawComplete?.()
          }, 200)
        },
      })
    })
  }, [animate, delay, replay])

  return (
    <div className={`${styles.weaveContainer}${className ? ` ${className}` : ''}`} aria-hidden="true">
      {/* Stroke layer — draw-on animation, fades out when brush appears */}
      <svg
        ref={svgRef}
        className={`${styles.shapeStroke} ${brushVisible ? styles.shapeStrokeHidden : ''}`}
        viewBox="0 0 199 135"
        fill="none"
        style={{ width: '100%', height: 'auto' }}
      >
        <GradientDef colors={gradientColors} />
        <path
          d={WEAVE_STROKE_PATH}
          stroke={fillColor}
          strokeWidth="3"
          fill="none"
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      </svg>

      {/* Brush layer — fades in after draw-on (final resting state) */}
      <div className={`${styles.shapeBrush} ${brushVisible ? styles.shapeBrushVisible : ''}`}>
        <svg viewBox="0 0 200 132" fill="none" style={{ width: '100%', height: 'auto' }}>
          <GradientDef colors={gradientColors} />
          <path d={WEAVE_BRUSH_PATH} fill={fillColor} />
        </svg>
      </div>
    </div>
  )
}
